// Render the poster: vector PDF (A0, scales to A1/A2) + PNG preview. usage: node render.mjs
import { createRequire } from 'node:module';
import { readdirSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const npx = `${homedir()}/.npm/_npx`;
const pdir = readdirSync(npx).map((d) => `${npx}/${d}/node_modules/puppeteer-core`).find((p) => existsSync(p));
const puppeteer = createRequire(pdir + '/package.json')(pdir);
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', defaultViewport: { width: 3179, height: 4494, deviceScaleFactor: 0.5 } });
const p = await b.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('requestfailed', (r) => errs.push('failed ' + r.url()));
await p.goto('file://' + path.join(HERE, process.env.SRC || 'poster.html'), { waitUntil: 'networkidle0' });
await p.evaluate(() => document.fonts.ready);
const over = await p.evaluate(() => { const r = document.getElementById('poster'); const out = []; r.querySelectorAll('*').forEach((e) => { const b = e.getBoundingClientRect(); if (b.bottom > 4494 + 1 || b.right > 3179 + 1) out.push(e.tagName + ' ' + (e.className || '') + ' ' + Math.round(b.right) + 'x' + Math.round(b.bottom)); }); return out.slice(0, 10); });
await p.screenshot({ path: path.join(HERE, (process.env.OUT || 'Learn8_poster') + '_preview.png') });
await p.pdf({ path: path.join(HERE, (process.env.OUT || 'Learn8_poster') + '_A0.pdf'), width: '841mm', height: '1189mm', printBackground: true, pageRanges: '1' });
console.log('overflow', over, 'errors', errs);
await b.close();
